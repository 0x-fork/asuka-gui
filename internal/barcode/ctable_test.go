package barcode

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"unicode/utf8"
)

var updateC = flag.Bool("update-c", false, "rewrite platform/desktop/src/barcode_jis.c from jisX0208")

// TestCTable checks that platform/desktop/src/barcode_jis.c, JIS X 0208
// for the C port of this package (asuka_barcode.h), is jisX0208.
// -update-c writes it.
func TestCTable(t *testing.T) {
	var b strings.Builder
	b.WriteString("// Code generated by internal/barcode's TestCTable (go test ./internal/barcode -run CTable -update-c). DO NOT EDIT.\n\n")
	b.WriteString("// barcode_jis.c: JIS X 0208, row by row (94 cells each, 0 where\n// unassigned), for barcode.c's Shift JIS.\n#include <stdint.h>\n\n")
	b.WriteString("const uint16_t asuka_barcode_jis[94 * 94] = {\n")
	rs := []rune(jisX0208)
	if len(rs) != 94*94 {
		t.Fatalf("jisX0208 has %d characters", len(rs))
	}
	for i, r := range rs {
		if i%16 == 0 {
			b.WriteString("\t")
		}
		if r == utf8.RuneError {
			r = 0
		}
		if r > 0xFFFF {
			t.Fatalf("U+%X doesn't fit in 16 bits", r)
		}
		fmt.Fprintf(&b, "0x%04x,", r)
		if i%16 == 15 || i == len(rs)-1 {
			b.WriteString("\n")
		} else {
			b.WriteString(" ")
		}
	}
	b.WriteString("};\n")
	path := filepath.Join("..", "..", "platform", "desktop", "src", "barcode_jis.c")
	if *updateC {
		if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	have, err := os.ReadFile(path)
	if err != nil || string(have) != b.String() {
		t.Fatalf("%s isn't jisX0208: go test ./internal/barcode -run CTable -update-c", path)
	}
}
