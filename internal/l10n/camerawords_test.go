// TestCameraWords checks that std/camera/desktop/camera_words.c, the
// words of the camera's take dialog on Windows and Linux (Take Photo,
// Cancel) in each language Asuka is translated to, is the catalogs' (C
// can't read this package's catalogs: it carries its own copy).
// -update-words writes it.
func TestCameraWords(t *testing.T) {
	files, err := fs.Glob(FS(), "*.json")
	if err != nil {
		t.Fatal(err)
	}
	var tags []string
	for _, f := range files {
		tags = append(tags, strings.TrimSuffix(f, ".json"))
	}
	slices.Sort(tags)
	var b strings.Builder
	b.WriteString("// Code generated by internal/l10n's TestCameraWords (go test ./internal/l10n -update-words). DO NOT EDIT.\n\n")
	b.WriteString("// The take dialog's words, by language: internal/l10n's catalogs'.\n#include \"camera.h\"\n\nconst camera_word camera_words[] = {\n")
	for _, tag := range tags {
		data, err := fs.ReadFile(FS(), tag+".json")
		if err != nil {
			t.Fatal(err)
		}
		var m map[string]any
		if err := json.Unmarshal(data, &m); err != nil {
			t.Fatal(err)
		}
		take, _ := m["takePhoto"].(string)
		cancel, _ := m["cancel"].(string)
		if take == "" || cancel == "" {
			continue // English, then
		}
		fmt.Fprintf(&b, "\t{%s, %s, %s},\n", cQuote(tag), cQuote(take), cQuote(cancel))
	}
	b.WriteString("\t{0, 0, 0},\n};\n")
	path := filepath.Join("..", "..", "std", "camera", "desktop", "camera_words.c")
	if *updateWords {
		if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	have, err := os.ReadFile(path)
	if err != nil || string(have) != b.String() {
		t.Fatalf("%s isn't the catalogs' words: go test ./internal/l10n -run CameraWords -update-words", path)
	}
}

// cQuote is a C string literal of s (UTF-8 as is).
func cQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		switch c := s[i]; {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c < 0x20:
			fmt.Fprintf(&b, `\%03o`, c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}
