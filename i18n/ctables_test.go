var updateC = flag.Bool("update-c", false, "write the C core's tables (core/src/ui/i18n_gen.c)")

// The C core says messages (core/src/ui/i18n.c) by the same CLDR data as
// this package: its plural rules, translated from tables.go, its week and
// time data, likely subtags and parent locales. TestCTables checks
// i18n_gen.c is what this package's data makes; -update-c writes it.
func TestCTables(t *testing.T) {
	got := cTables(t)
	path := filepath.Join("..", "core", "src", "ui", "i18n_gen.c")
	if *updateC {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil || !bytes.Equal(got, want) {
		t.Fatalf("%s is stale: go test ./i18n -run CTables -update-c", path)
	}
}

func cTables(t *testing.T) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by go test ./i18n -run CTables -update-c from package i18n's CLDR " + CLDRVersion + " data. DO NOT EDIT.\n\n")
	b.WriteString("#include \"ui/i18n.h\"\n\n")
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "tables.go", nil, 0)
	if err != nil {
		t.Fatal(err)
	}
	for _, d := range f.Decls {
		fn, ok := d.(*ast.FuncDecl)
		if !ok || (fn.Name.Name != "cardinalRule" && fn.Name.Name != "ordinalRule") {
			continue
		}
		name := strings.TrimSuffix(fn.Name.Name, "Rule")
		fmt.Fprintf(&b, "uint8_t ak_i18n_%s_rule(uint8_t r, const ak_operands *o) {\n", name)
		for _, s := range fn.Body.List {
			cStmt(t, &b, s, "\t")
		}
		b.WriteString("}\n\n")
	}
	strs := func(name string, list []string) {
		fmt.Fprintf(&b, "const char *const %s[] = {", name)
		for i, s := range list {
			if i%10 == 0 {
				b.WriteString("\n\t")
			} else {
				b.WriteString(" ")
			}
			fmt.Fprintf(&b, "%q,", s)
		}
		b.WriteString("\n};\n")
	}
	ints := func(name string, list []uint8) {
		fmt.Fprintf(&b, "const uint8_t %s[] = {", name)
		for i, v := range list {
			if i%20 == 0 {
				b.WriteString("\n\t")
			} else {
				b.WriteString(" ")
			}
			fmt.Fprintf(&b, "%d,", v)
		}
		b.WriteString("\n};\n")
	}
	strs("ak_i18n_cardinal_langs", cardinalLangs[:])
	ints("ak_i18n_cardinal_rules", cardinalRules[:])
	fmt.Fprintf(&b, "const uint32_t ak_i18n_ncardinal = %d;\n\n", len(cardinalLangs))
	strs("ak_i18n_ordinal_langs", ordinalLangs[:])
	ints("ak_i18n_ordinal_rules", ordinalRules[:])
	fmt.Fprintf(&b, "const uint32_t ak_i18n_nordinal = %d;\n\n", len(ordinalLangs))

	// Regions: their first day of the week and hour cycle.
	loadTables()
	seen := map[string]bool{}
	var regions []string
	for _, r := range tables.weekRegions {
		if !seen[r] {
			seen[r] = true
			regions = append(regions, r)
		}
	}
	for _, k := range tables.hourKeys {
		if !strings.Contains(k, "-") && !seen[k] {
			seen[k] = true
			regions = append(regions, k)
		}
	}
	sort.Strings(regions)
	b.WriteString("const ak_i18n_region_data ak_i18n_regions[] = {")
	for i, r := range regions {
		day, _ := weekData(r)
		hc := 24
		if h := preferredHour("", r); h == 'h' || h == 'K' {
			hc = 12
		}
		if i%6 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "{%q, %d, %d},", r, int(day)+1, hc)
	}
	fmt.Fprintf(&b, "\n};\nconst uint32_t ak_i18n_nregions = %d;\n\n", len(regions))

	// Languages' likely scripts and regions.
	langs := map[string]bool{}
	addLang := func(tag string) {
		if l, _, _ := strings.Cut(tag, "-"); l != "" && l != "und" && l != "root" {
			langs[l] = true
		}
	}
	for _, l := range cardinalLangs {
		addLang(l)
	}
	for _, l := range ordinalLangs {
		addLang(l)
	}
	for _, l := range tables.locales {
		addLang(l)
	}
	for _, l := range parentChildren {
		addLang(l)
	}
	var sorted []string
	for l := range langs {
		sorted = append(sorted, l)
	}
	sort.Strings(sorted)
	b.WriteString("const ak_i18n_likely ak_i18n_likelies[] = {")
	n := 0
	for _, l := range sorted {
		tag, err := language.Parse(l)
		if err != nil {
			continue
		}
		s, sc := tag.Script()
		r, rc := tag.Region()
		script, region := s.String(), r.String()
		if sc == language.No || script == "Zzzz" {
			script = ""
		}
		if rc == language.No || region == "ZZ" {
			region = ""
		}
		if n%4 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		n++
		fmt.Fprintf(&b, "{%q, %q, %q},", l, script, region)
	}
	fmt.Fprintf(&b, "\n};\nconst uint32_t ak_i18n_nlikelies = %d;\n\n", n)

	// Parent locales: child, parent.
	b.WriteString("const char *const ak_i18n_parents[] = {")
	for i, c := range parentChildren {
		if i%4 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "%q, %q,", c, parentLocales[i])
	}
	fmt.Fprintf(&b, "\n};\nconst uint32_t ak_i18n_nparents = %d;\n\n", len(parentChildren))

	// Currencies: the fraction digits of those of other than two, and how
	// English, the formats of an app without catalogs, writes amounts.
	b.WriteString("const char *const ak_i18n_currency_digits[] = {")
	digits := strings.Fields(fmtCurrencyDigits)
	for i, d := range digits {
		if i%10 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "%q,", d)
	}
	fmt.Fprintf(&b, "\n};\nconst uint32_t ak_i18n_ncurrency_digits = %d;\n\n", len(digits))
	en := keyOf("en").dat().numbers(true)
	b.WriteString("const ak_i18n_pattern ak_i18n_en_currency[2] = {\n")
	for _, p := range []*numberPattern{&en.currency, &en.currencyAlpha} {
		fmt.Fprintf(&b, "\t{%s, %s, %s, %s, %d, %d, %d, %d},\n", cQuote(p.prefix), cQuote(p.suffix), cQuote(p.negPrefix), cQuote(p.negSuffix), p.primary, p.secondary, p.minInt, p.maxFrac)
	}
	fmt.Fprintf(&b, "};\nconst char ak_i18n_en_currency_spacing[] = %s;\n", cQuote(en.currencySpacing))
	if en.currencyDecimal != "" || en.currencyGroup != "" {
		t.Fatal("English has separators of amounts of their own: the core's English has none")
	}
	b.WriteString("const ak_i18n_currency ak_i18n_en_currencies[] = {")
	curs := Currencies("en")
	for i, c := range curs {
		if c.Pattern != "" || c.Decimal != "" || c.Group != "" {
			t.Fatalf("English writes %s in a pattern of its own: the core's English has none", c.Code)
		}
		if i%4 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "{%q, %s, %d},", c.Code, cQuote(c.Symbol), c.flags())
	}
	fmt.Fprintf(&b, "\n};\nconst uint32_t ak_i18n_nen_currencies = %d;\n", len(curs))
	return b.Bytes()
}

// cQuote is s as a C string literal: printable ASCII as it is, other
// bytes in octal (which, unlike \x, ends after three digits).
func cQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c >= 0x20 && c < 0x7f:
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "\\%03o", c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

var cPlurals = map[string]string{
	"PluralZero": "AK_PLURAL_ZERO", "PluralOne": "AK_PLURAL_ONE", "PluralTwo": "AK_PLURAL_TWO",
	"PluralFew": "AK_PLURAL_FEW", "PluralMany": "AK_PLURAL_MANY", "PluralOther": "AK_PLURAL_OTHER",
}

func cStmt(t *testing.T, b *bytes.Buffer, s ast.Stmt, indent string) {
	switch s := s.(type) {
	case *ast.SwitchStmt:
		fmt.Fprintf(b, "%sswitch (%s) {\n", indent, cExpr(t, s.Tag))
		for _, c := range s.Body.List {
			cc := c.(*ast.CaseClause)
			for _, e := range cc.List {
				fmt.Fprintf(b, "%scase %s:\n", indent, cExpr(t, e))
			}
			for _, st := range cc.Body {
				cStmt(t, b, st, indent+"\t")
			}
			fmt.Fprintf(b, "%s\tbreak;\n", indent)
		}
		fmt.Fprintf(b, "%s}\n", indent)
	case *ast.IfStmt:
		if s.Init != nil || s.Else != nil {
			t.Fatalf("tables.go: an if the C translation doesn't take")
		}
		fmt.Fprintf(b, "%sif (%s) {\n", indent, cExpr(t, s.Cond))
		for _, st := range s.Body.List {
			cStmt(t, b, st, indent+"\t")
		}
		fmt.Fprintf(b, "%s}\n", indent)
	case *ast.ReturnStmt:
		fmt.Fprintf(b, "%sreturn %s;\n", indent, cExpr(t, s.Results[0]))
	default:
		t.Fatalf("tables.go: a %T the C translation doesn't take", s)
	}
}

func cExpr(t *testing.T, e ast.Expr) string {
	switch e := e.(type) {
	case *ast.BinaryExpr:
		x, y := cExpr(t, e.X), cExpr(t, e.Y)
		if e.Op == token.LOR {
			// C wants an && inside an || in parentheses (-Wlogical-op-parentheses).
			if b, ok := e.X.(*ast.BinaryExpr); ok && b.Op == token.LAND {
				x = "(" + x + ")"
			}
			if b, ok := e.Y.(*ast.BinaryExpr); ok && b.Op == token.LAND {
				y = "(" + y + ")"
			}
		}
		return x + " " + e.Op.String() + " " + y
	case *ast.UnaryExpr:
		return e.Op.String() + cExpr(t, e.X)
	case *ast.ParenExpr:
		return "(" + cExpr(t, e.X) + ")"
	case *ast.BasicLit:
		if e.Kind == token.INT {
			return e.Value
		}
	case *ast.Ident:
		if c, ok := cPlurals[e.Name]; ok {
			return c
		}
		if e.Name == "r" {
			return "r"
		}
	case *ast.SelectorExpr:
		if x, ok := e.X.(*ast.Ident); ok && x.Name == "o" {
			return "o->" + strings.ToLower(e.Sel.Name)
		}
	case *ast.CallExpr:
		if f, ok := e.Fun.(*ast.Ident); ok && len(e.Args) == 1 {
			switch f.Name {
			case "uint64":
				return "(uint64_t)(" + cExpr(t, e.Args[0]) + ")"
			case "int":
				return "(int)(" + cExpr(t, e.Args[0]) + ")"
			}
		}
	}
	t.Fatalf("tables.go: an expression the C translation doesn't take: %T", e)
	return ""
}
