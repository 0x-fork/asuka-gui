//go:build ignore

// gen_symbols writes the Linux host's fallback symbols
// (src/symbols_gen.c): the SF Symbol names ui.Symbol and ui.Icon take
// that the icon theme has no icon for are drawn as Material Symbols
// (Apache 2.0), as the Android and web hosts draw them, read from the web
// host's table, which platform/web/gen_symbols.go writes. Run it after
// that one:
//
//	go run platform/linux/gen_symbols.go
package main

import (
	"bytes"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var (
	pathRe  = regexp.MustCompile(`(?m)^  "([^"]*)",$`)
	entryRe = regexp.MustCompile(`(?m)^  "([^"]+)": p\[(\d+)\],$`)
	labelRe = regexp.MustCompile(`(?m)^  "([^"]+)": "([^"]*)",$`)
)

type entry struct {
	name string
	v    string
}

func main() {
	js, err := os.ReadFile("platform/web/src/symbols.js")
	if err != nil {
		panic(err)
	}
	src := string(js)
	pathsPart, rest, _ := strings.Cut(src, "export const paths")
	entriesPart, labelsPart, _ := strings.Cut(rest, "export const labels")
	var b bytes.Buffer
	b.WriteString("// Code generated by platform/linux/gen_symbols.go; DO NOT EDIT.\n\n#include \"symbols.h\"\n\n")
	b.WriteString("// Material Symbols (Apache 2.0) as SVG path data, in Material's\n// 960-unit box, whose y runs from -960 to 0.\nconst char *const lx_material_paths[] = {\n")
	for _, m := range pathRe.FindAllStringSubmatch(pathsPart, -1) {
		fmt.Fprintf(&b, "\t%s,\n", strconv.Quote(m[1]))
	}
	b.WriteString("};\n\n")
	var entries, labels []entry
	for _, m := range entryRe.FindAllStringSubmatch(entriesPart, -1) {
		entries = append(entries, entry{m[1], m[2]})
	}
	for _, m := range labelRe.FindAllStringSubmatch(labelsPart, -1) {
		labels = append(labels, entry{m[1], m[2]})
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].name < entries[j].name })
	sort.Slice(labels, func(i, j int) bool { return labels[i].name < labels[j].name })
	b.WriteString("// The SF Symbol names drawn with lx_material_paths, sorted.\nconst lx_symbol_path lx_material_symbols[] = {\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t{%s, %s},\n", strconv.Quote(e.name), e.v)
	}
	b.WriteString("};\nconst size_t lx_material_symbol_count = sizeof lx_material_symbols / sizeof *lx_material_symbols;\n\n")
	b.WriteString("// What screen readers say for a symbol, sorted.\nconst lx_symlabel lx_symbol_labels[] = {\n")
	for _, e := range labels {
		fmt.Fprintf(&b, "\t{%s, %s},\n", strconv.Quote(e.name), strconv.Quote(e.v))
	}
	b.WriteString("};\nconst size_t lx_symbol_label_count = sizeof lx_symbol_labels / sizeof *lx_symbol_labels;\n")
	if err := os.WriteFile("platform/linux/src/symbols_gen.c", b.Bytes(), 0o644); err != nil {
		panic(err)
	}
}
