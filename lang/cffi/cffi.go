// Package cffi generates the C glue of a program's extern declarations
// (RFC 0008, docs/c.md, lang/LOWERING.md "C from Asuka"): for each
// extern fn, a builtin (core/src/vm/vm.h's calling convention) that
// converts its arguments from Asuka's values to C's types, calls the C
// function, and converts its result back; a trampoline per callback
// signature, through which C calls an Asuka closure; and
// asuka_ffi_register, which registers the builtins under the names the
// bytecode calls them by (check.ExternBuiltin). The CLI compiles the
// glue into the core's build (internal/appbuild), with the C it calls.
//
// The glue declares each C function itself, from its extern
// declaration, under a name of its own bound to the C symbol
// (AK_FFI_SYM), so it needs none of the library's headers and no name
// it declares clashes with one.
package cffi

import (
	"bytes"
	"fmt"
	"sort"
	"strings"

	"github.com/egoist/asuka/lang/check"
)

// Generate is the glue of prog's extern declarations; nil when it has
// none.
func Generate(prog *check.Program) ([]byte, error) {
	g := &gen{pkgIndex: map[*check.Package]int{}, tramps: map[string]string{}}
	var pkgs []*check.Package
	for _, p := range prog.Packages {
		if hasExterns(p) {
			pkgs = append(pkgs, p)
		}
	}
	if len(pkgs) == 0 {
		return nil, nil
	}
	sort.SliceStable(pkgs, func(i, j int) bool { return pkgs[i].Path < pkgs[j].Path })
	for i, p := range pkgs {
		if i > 0 && pkgs[i-1].Path == p.Path {
			return nil, fmt.Errorf("two packages %s (%s and %s) declare externs: their builtins would share names", label(p), pkgs[i-1].Dir, p.Dir)
		}
		g.pkgIndex[p] = i
	}
	g.p("// Code generated by asuka (lang/cffi) from the program's extern declarations. DO NOT EDIT.\n\n")
	g.p("#include \"vm/vm.h\"\n#include \"vm/ffi.h\"\n\n#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n")
	g.p("#define AK_FFI_UNUSED __attribute__((unused))\n\n")
	// Structs first, every package's, each after those it holds.
	done := map[*check.TypeName]bool{}
	for _, p := range pkgs {
		for _, t := range p.Types {
			if t.Kind == check.StructType && t.Extern {
				g.structDecl(t, done)
			}
		}
	}
	for _, p := range pkgs {
		g.pkg(p)
	}
	g.p("void asuka_ffi_register(void);\nvoid asuka_ffi_register(void) {\n")
	for _, r := range g.regs {
		g.p("\tak_builtin_register(%q, %s);\n", r[0], r[1])
	}
	g.p("}\n")
	return g.b.Bytes(), nil
}

func hasExterns(p *check.Package) bool {
	for _, f := range p.Funcs {
		if f.Extern != nil {
			return true
		}
	}
	for _, t := range p.Types {
		if t.Kind == check.ExternType || t.Kind == check.StructType && t.Extern {
			return true
		}
	}
	return false
}

func label(p *check.Package) string {
	if p.Path == "" {
		return "main"
	}
	return p.Path
}

type gen struct {
	b        bytes.Buffer
	pkgIndex map[*check.Package]int
	tramps   map[string]string // a callback's signature → its trampoline
	ntramp   int
	regs     [][2]string // builtin name, C function
}

func (g *gen) p(format string, args ...any) { fmt.Fprintf(&g.b, format, args...) }

// prefix names what the glue declares for package p.
func (g *gen) prefix(p *check.Package) string { return fmt.Sprintf("ak_ffi_%d_", g.pkgIndex[p]) }

func (g *gen) structName(t *check.TypeName) string { return g.prefix(t.Pkg) + "s_" + t.Name() }

// ctype is t's C type, for a declaration.
func (g *gen) ctype(t *check.CType) string {
	switch t.Kind {
	case check.CVoid:
		return "void"
	case check.CInt8:
		return "int8_t"
	case check.CInt16:
		return "int16_t"
	case check.CInt32:
		return "int32_t"
	case check.CInt64:
		return "int64_t"
	case check.CUInt8:
		return "uint8_t"
	case check.CUInt16:
		return "uint16_t"
	case check.CUInt32:
		return "uint32_t"
	case check.CUInt64:
		return "uint64_t"
	case check.CFloat32:
		return "float"
	case check.CDouble:
		return "double"
	case check.CBool:
		return "bool"
	case check.CString:
		return "const char *"
	case check.CPointer, check.CExtern:
		return "void *"
	case check.CStruct:
		return g.structName(t.Named)
	}
	panic(fmt.Sprintf("cffi: no C type for %d", t.Kind))
}

// cparams are t's C parameter types: one, or two for bytes and
// callbacks.
func (g *gen) cparams(t *check.CType) []string {
	switch t.Kind {
	case check.CBytes:
		return []string{"const uint8_t *", "size_t"}
	case check.CFunc:
		ps := []string{"void *"}
		for _, p := range t.Func.Params {
			ps = append(ps, g.ctype(p))
		}
		return []string{g.ctype(t.Func.Result) + " (*)(" + strings.Join(ps, ", ") + ")", "void *"}
	}
	return []string{g.ctype(t)}
}

// kind is the ak_kind of the Asuka value a C type crosses as.
func kind(t *check.CType) string {
	switch {
	case t.Kind == check.CVoid:
		return "AK_K_VOID"
	case t.IsInt():
		return "AK_K_INT"
	case t.Kind == check.CPointer && !t.Opt:
		return "AK_K_INT"
	case t.Kind == check.CFloat32 || t.Kind == check.CDouble:
		return "AK_K_FLOAT"
	case t.Kind == check.CBool:
		return "AK_K_BOOL"
	}
	return "AK_K_REF"
}

// scalarIn is the C value of the Asuka value v (an ak_val expression)
// of a scalar C type; "" for the others.
func (g *gen) scalarIn(t *check.CType, v string) string {
	switch {
	case t.IsInt():
		return fmt.Sprintf("(%s)%s.i", g.ctype(t), v)
	case t.Kind == check.CFloat32:
		return fmt.Sprintf("(float)%s.f", v)
	case t.Kind == check.CDouble:
		return v + ".f"
	case t.Kind == check.CBool:
		return v + ".i != 0"
	case t.Kind == check.CPointer && !t.Opt:
		return fmt.Sprintf("(void *)(intptr_t)%s.i", v)
	case t.Kind == check.CPointer:
		return fmt.Sprintf("(%s.p ? (void *)(intptr_t)((const ak_box *)%s.p)->v.i : NULL)", v, v)
	case t.Kind == check.CString:
		return fmt.Sprintf("(%s.p ? (const char *)((const ak_str *)%s.p)->data : NULL)", v, v)
	}
	return ""
}

// scalarOut is the Asuka value (an ak_val expression) of the C value x
// of a scalar C type; "" for the others.
func scalarOut(t *check.CType, x string) string {
	switch {
	case t.IsInt():
		return fmt.Sprintf("(ak_val){.i = (int64_t)%s}", x)
	case t.Kind == check.CFloat32 || t.Kind == check.CDouble:
		return fmt.Sprintf("(ak_val){.f = (double)%s}", x)
	case t.Kind == check.CBool:
		return fmt.Sprintf("(ak_val){.i = %s ? 1 : 0}", x)
	case t.Kind == check.CPointer && !t.Opt:
		return fmt.Sprintf("(ak_val){.i = (int64_t)(intptr_t)%s}", x)
	case t.Kind == check.CPointer:
		return fmt.Sprintf("(%s ? (ak_val){.p = ak_box_new(AK_K_INT, (ak_val){.i = (int64_t)(intptr_t)%s})} : (ak_val){.p = NULL})", x, x)
	}
	return ""
}

// structDecl declares an extern struct (after those it holds), and its
// conversions: from the Asuka struct (borrowed) to C's, and back, of a
// shape.
func (g *gen) structDecl(t *check.TypeName, done map[*check.TypeName]bool) {
	if done[t] {
		return
	}
	done[t] = true
	for _, f := range t.Fields {
		if f.C != nil && f.C.Kind == check.CStruct {
			g.structDecl(f.C.Named, done)
		}
	}
	name := g.structName(t)
	g.p("// extern struct %s (%s)\n", t.Name(), label(t.Pkg))
	g.p("typedef struct %s {\n", name)
	for i, f := range t.Fields {
		g.p("\t%s f%d; // %s\n", g.ctype(f.C), i, f.Name)
	}
	if len(t.Fields) == 0 {
		g.p("\tchar unused;\n")
	}
	g.p("} %s;\n\n", name)
	g.p("static AK_FFI_UNUSED void %s_in(ak_val v, %s *o) {\n", name, name)
	g.p("\tconst ak_struct *s = v.p;\n")
	if len(t.Fields) == 0 {
		g.p("\t(void)s;\n\t(void)o;\n")
	}
	for i, f := range t.Fields {
		if f.C.Kind == check.CStruct {
			g.p("\t%s_in(s->f[%d], &o->f%d);\n", g.structName(f.C.Named), i, i)
			continue
		}
		g.p("\to->f%d = %s;\n", i, g.scalarIn(f.C, fmt.Sprintf("s->f[%d]", i)))
	}
	g.p("}\n\n")
	g.p("static AK_FFI_UNUSED ak_val %s_out(const %s *o, const ak_shape *shape) {\n", name, name)
	g.p("\tak_struct *s = ak_struct_new(shape);\n")
	if len(t.Fields) == 0 {
		g.p("\t(void)o;\n")
	}
	for i, f := range t.Fields {
		if f.C.Kind == check.CStruct {
			g.p("\ts->f[%d] = %s_out(&o->f%d, shape->shapes[%d]);\n", i, g.structName(f.C.Named), i, i)
			continue
		}
		g.p("\ts->f[%d] = %s;\n", i, scalarOut(f.C, fmt.Sprintf("o->f%d", i)))
	}
	g.p("\treturn (ak_val){.p = s};\n}\n\n")
}

// pkg writes a package's C declarations, release functions and
// wrappers.
func (g *gen) pkg(p *check.Package) {
	pre := g.prefix(p)
	g.p("// ---- package %s ----\n\n", label(p))
	var fns []*check.Function
	for _, f := range p.Funcs {
		if f.Extern != nil {
			fns = append(fns, f)
		}
	}
	for _, f := range fns {
		var ps []string
		for _, t := range f.Extern.Params {
			ps = append(ps, g.cparams(t)...)
		}
		if len(ps) == 0 {
			ps = []string{"void"}
		}
		g.p("extern %s %sc_%s(%s) __asm__(AK_FFI_SYM(%q));\n", g.ctype(f.Extern.Result), pre, f.Name(), strings.Join(ps, ", "), f.Name())
	}
	g.p("\n")
	for _, t := range p.Types {
		if t.Kind != check.ExternType || t.Release == nil {
			continue
		}
		g.p("static void %srelease_%s(void *p) { %s%sc_%s(p); }\n\n", pre, t.Name(), voidCast(t.Release.Extern.Result), pre, t.Release.Name())
	}
	for _, f := range fns {
		g.wrapper(f)
	}
}

func voidCast(t *check.CType) string {
	if t.Kind == check.CVoid {
		return ""
	}
	return "(void)"
}

// trampoline is the C function C calls a callback of type t through,
// written once per signature.
func (g *gen) trampoline(t *check.CFuncType) string {
	var key strings.Builder
	key.WriteString(g.ctype(t.Result))
	for _, p := range t.Params {
		fmt.Fprintf(&key, ",%s%v", g.ctype(p), p.Opt)
	}
	key.WriteString(";" + kind(t.Result) + fmt.Sprint(t.Result.Opt))
	if name, ok := g.tramps[key.String()]; ok {
		return name
	}
	name := fmt.Sprintf("ak_ffi_cb_%d", g.ntramp)
	g.ntramp++
	g.tramps[key.String()] = name
	ps := []string{"void *ctx"}
	for i, p := range t.Params {
		ps = append(ps, fmt.Sprintf("%s a%d", g.ctype(p), i))
	}
	n := len(t.Params)
	g.p("static %s %s(%s) {\n", g.ctype(t.Result), name, strings.Join(ps, ", "))
	g.p("\tak_val v[%d] = {{0}};\n", max(n, 1))
	kinds := make([]string, n)
	for i, p := range t.Params {
		kinds[i] = kind(p)
		a := fmt.Sprintf("a%d", i)
		if p.Kind == check.CString {
			g.p("\tv[%d] = ak_ffi_str_arg(%s, %v);\n", i, a, p.Opt)
			continue
		}
		g.p("\tv[%d] = %s;\n", i, scalarOut(p, a))
	}
	if n == 0 {
		kinds = []string{"AK_K_VOID"}
	}
	g.p("\tstatic const uint8_t kinds[%d] = {%s};\n", max(n, 1), strings.Join(kinds, ", "))
	g.p("\tak_val r = ak_ffi_cb_call(ctx, v, kinds, %d, %s);\n", n, kind(t.Result))
	switch {
	case t.Result.Kind == check.CVoid:
		g.p("\t(void)r;\n")
	case t.Result.Kind == check.CPointer && t.Result.Opt:
		g.p("\tvoid *out = %s;\n\tak_release(r.p);\n\treturn out;\n", g.scalarIn(t.Result, "r"))
	default:
		g.p("\treturn %s;\n", g.scalarIn(t.Result, "r"))
	}
	g.p("}\n\n")
	return name
}

// wrapper writes f's builtin.
func (g *gen) wrapper(f *check.Function) {
	ext := f.Extern
	pre := g.prefix(f.Pkg)
	// Trampolines before the wrapper that names them.
	tramps := make([]string, len(ext.Params))
	for i, t := range ext.Params {
		if t.Kind == check.CFunc {
			tramps[i] = g.trampoline(t.Func)
		}
	}
	fn := pre + f.Name()
	g.p("// %s\n", f.Name())
	g.p("static ak_val %s(ak_val *a, uint32_t n) {\n\t(void)n;\n", fn)
	var args []string
	var cbs []string
	// The values that may throw (a released extern type) first; then,
	// once nothing can fail, what allocates (callbacks).
	for i, t := range ext.Params {
		v := fmt.Sprintf("a[%d]", i)
		switch t.Kind {
		case check.CExtern:
			g.p("\tvoid *x%d = ak_ffi_ptr(%s, %q);\n", i, v, f.Name())
			args = append(args, fmt.Sprintf("x%d", i))
		case check.CStruct:
			g.p("\t%s s%d;\n\t%s_in(%s, &s%d);\n", g.structName(t.Named), i, g.structName(t.Named), v, i)
			args = append(args, fmt.Sprintf("s%d", i))
		case check.CBytes:
			g.p("\tconst ak_bytes *b%d = %s.p;\n", i, v)
			args = append(args, fmt.Sprintf("b%d ? b%d->data : NULL", i, i), fmt.Sprintf("b%d ? (size_t)b%d->len : 0", i, i))
		case check.CFunc:
			cbs = append(cbs, fmt.Sprintf("c%d", i))
			args = append(args, fmt.Sprintf("c%d ? %s : NULL", i, tramps[i]), fmt.Sprintf("c%d", i))
		default:
			args = append(args, g.scalarIn(t, v))
		}
	}
	g.p("\tif (ak_error_pending()) return (ak_val){0};\n")
	for i, t := range ext.Params {
		if t.Kind == check.CFunc {
			g.p("\tak_ffi_cb *c%d = ak_ffi_cb_new(a[%d]);\n", i, i)
		}
	}
	call := fmt.Sprintf("%sc_%s(%s)", pre, f.Name(), strings.Join(args, ", "))
	res := ext.Result
	g.p("\tak_ffi_enter();\n")
	if res.Kind == check.CVoid {
		g.p("\t%s;\n", call)
	} else {
		g.p("\t%s r = %s;\n", g.ctype(res), call)
	}
	g.p("\tak_ffi_leave();\n")
	for _, c := range cbs {
		g.p("\tak_ffi_cb_done(%s);\n", c)
	}
	if ext.Releases != nil {
		g.p("\tak_ffi_released(a[0]);\n")
	}
	switch {
	case res.Kind == check.CVoid:
		g.p("\treturn (ak_val){0};\n")
	case res.Kind == check.CExtern:
		release := "NULL"
		if res.Named.Release != nil {
			release = g.prefix(res.Named.Pkg) + "release_" + res.Named.Name()
		}
		g.p("\tif (ak_error_pending()) {\n")
		if release != "NULL" {
			g.p("\t\tif (r) %s(r);\n", release)
		}
		g.p("\t\treturn (ak_val){0};\n\t}\n")
		g.p("\treturn ak_ffi_obj_new(r, %s, %q, %v, %q);\n", release, res.Named.Name(), res.Opt, f.Name())
	case res.Kind == check.CString:
		g.p("\tif (ak_error_pending()) return (ak_val){0};\n")
		g.p("\treturn ak_ffi_str(r, %v, %q);\n", res.Opt, f.Name())
	case res.Kind == check.CStruct:
		g.p("\tif (ak_error_pending()) return (ak_val){0};\n")
		g.p("\treturn %s_out(&r, ((const ak_struct *)a[n - 1].p)->shape);\n", g.structName(res.Named))
	default:
		if kind(res) == "AK_K_REF" {
			g.p("\tif (ak_error_pending()) return (ak_val){0};\n")
		}
		g.p("\treturn %s;\n", scalarOut(res, "r"))
	}
	g.p("}\n\n")
	g.regs = append(g.regs, [2]string{ext.Builtin, fn})
}
