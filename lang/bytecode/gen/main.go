// Command gen writes the VM's opcode header (core/src/vm/opcodes_gen.h)
// from lang/bytecode's table.
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/egoist/asuka/lang/bytecode"
)

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by lang/bytecode/gen from lang/bytecode/opcodes.go. DO NOT EDIT.\n\n")
	b.WriteString("#ifndef AK_VM_OPCODES_GEN_H\n#define AK_VM_OPCODES_GEN_H\n\n")
	fmt.Fprintf(&b, "#define AK_BC_VERSION %d\n\n", bytecode.Version)
	b.WriteString("enum {\n")
	for i, d := range bytecode.Ops {
		ops := make([]string, len(d.Operands))
		for j, o := range d.Operands {
			ops[j] = [...]string{"", "reg", "imm", "const", "func", "shape", "builtin", "kind", "off", "global"}[o]
		}
		fmt.Fprintf(&b, "\tAK_OP_%s = %d, // %s: %s\n", d.Name, i, strings.Join(ops, " "), d.Doc)
	}
	fmt.Fprintf(&b, "\tAK_OP__COUNT = %d,\n};\n\n", len(bytecode.Ops))
	b.WriteString("// Instruction widths in words.\nstatic const uint8_t ak_op_width[] = {")
	for i := range bytecode.Ops {
		if i%16 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "%d,", bytecode.Op(i).Width())
	}
	b.WriteString("\n};\n\nstatic const char *const ak_op_names[] = {")
	for i, d := range bytecode.Ops {
		if i%8 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "%q,", d.Name)
	}
	b.WriteString("\n};\n\n#endif\n")
	out := filepath.Join("..", "..", "core", "src", "vm", "opcodes_gen.h")
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(out, b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
