// Command gen writes conformance/app/app.asuka: the conformance sheet's
// app, from the cases (go generate ./conformance).
package main

import (
	"log"
	"os"

	"github.com/egoist/asuka/conformance"
)

func main() {
	src := "// Code generated by go generate ./conformance. DO NOT EDIT.\n\n// The conformance sheet (package conformance), for its runners to\n// capture or to look at: asuka dev --platform ios conformance/app\n\n" + conformance.App()
	if err := os.WriteFile("app/app.asuka", []byte(src), 0o644); err != nil {
		log.Fatal(err)
	}
}
